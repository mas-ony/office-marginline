import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Node as PMNode } from 'prosemirror-model';

/** This folder (tests/unit); `new URL(…, import.meta.url)` would be rewritten by Vite. */
const here = dirname(fileURLToPath(import.meta.url));

export function fixture(name: string): Uint8Array {
  return new Uint8Array(readFileSync(join(here, '../fixtures', name)));
}

/** First text node whose text equals `text`, with its marks by type name. */
export function findText(doc: PMNode, text: string): PMNode | undefined {
  let found: PMNode | undefined;
  doc.descendants((n) => {
    if (found) return false;
    if (n.isText && n.text === text) found = n;
    return true;
  });
  return found;
}

export function markOf(node: PMNode | undefined, name: string) {
  return node?.marks.find((m) => m.type.name === name);
}

export function nodesOfType(doc: PMNode, type: string): PMNode[] {
  const out: PMNode[] = [];
  doc.descendants((n) => {
    if (n.type.name === type) out.push(n);
    return true;
  });
  return out;
}

/** JSON of a document with volatile attributes (raw XML, URLs, revision ids) removed. */
export function stableJson(doc: PMNode): unknown {
  const strip = (value: unknown): unknown => {
    if (Array.isArray(value)) return value.map(strip);
    if (value && typeof value === 'object') {
      const out: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(value)) {
        if (['raw', 'xml', 'src', 'part', 'markRaw', 'pPrChange'].includes(k)) continue;
        out[k] = strip(v);
      }
      const mark = out as { type?: string; attrs?: Record<string, unknown> };
      if (mark.type && ['insertion', 'deletion', 'formatChange'].includes(mark.type) && mark.attrs) delete mark.attrs.id;
      if (mark.attrs && 'trackIns' in mark.attrs && mark.attrs.trackIns) delete (mark.attrs.trackIns as Record<string, unknown>).id;
      if (mark.attrs && 'trackDel' in mark.attrs && mark.attrs.trackDel) delete (mark.attrs.trackDel as Record<string, unknown>).id;
      return out;
    }
    return value;
  };
  return strip(doc.toJSON());
}

